// Makes the two images the shared email template uses, and the module that
// carries them inside each email (api/_emailImages.js), so they show in
// every inbox whichever deployment sent the email (a preview is behind a
// login, so an email can't rely on a link back to the site).
//
//   node scripts/make-email-images.mjs
//
//   - the bold crosshair for portal emails: drawn from the portal's one
//     shared drawing (src/lib/boldCrosshair.js), never redrawn here, in
//     black for the light email, at twice its 24px display size;
//   - The Clarity Project's horizontal logo in black for Leading Ideas: the
//     designer's own file (public/brand/the-clarity-project-horizontal-black.png),
//     only made smaller (twice its 220px display size), never altered.
import { chromium } from 'playwright';
import { readFileSync, writeFileSync } from 'node:fs';
import { BOLD_CROSS_PATHS, BOLD_CROSS_STROKE, BOLD_CROSS_VIEWBOX } from '../src/lib/boldCrosshair.js';

const SIZE = 48; // 24px shown, at twice the size
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${BOLD_CROSS_VIEWBOX.join(' ')}" width="${SIZE}" height="${SIZE}"><g fill="none" stroke="#000" stroke-width="${BOLD_CROSS_STROKE}" stroke-linejoin="round">${BOLD_CROSS_PATHS.map((p) => `<path d="${p.d}" transform="translate(${p.dx.toFixed(2)} ${p.dy.toFixed(2)})"/>`).join('')}</g></svg>`;

const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: SIZE, height: SIZE }, deviceScaleFactor: 1 });
await page.setContent(`<body style="margin:0;background:transparent">${svg}</body>`);
const crosshair = await page.locator('svg').screenshot({ omitBackground: true });
await browser.close();
writeFileSync('public/brand/bold-crosshair-black-email@2x.png', crosshair);

const logo = readFileSync('public/brand/the-clarity-project-horizontal-black-email@2x.png');
writeFileSync('api/_emailImages.js', `// Generated by scripts/make-email-images.mjs: the shared email template's two
// images, embedded so they travel inside each email as inline images
// (referenced by content ID). Never edited by hand. The file name starts
// with an underscore so Vercel does not publish it as a route.
export const EMAIL_IMAGE_BASE64 = {
  crosshair: '${crosshair.toString('base64')}',
  project: '${logo.toString('base64')}',
};
`);
console.log(`Made the bold crosshair (${crosshair.length} bytes) and the logo module (${logo.length} bytes).`);
